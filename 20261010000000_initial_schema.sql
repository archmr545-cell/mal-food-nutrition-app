create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_name text;
  birth_day_value integer;
  birth_month_value integer;
  birth_year_value integer;
begin
  profile_name := btrim(coalesce(new.raw_user_meta_data ->> 'name', ''));
  birth_day_value := (new.raw_user_meta_data ->> 'birth_day')::integer;
  birth_month_value := (new.raw_user_meta_data ->> 'birth_month')::integer;
  birth_year_value := (new.raw_user_meta_data ->> 'birth_year')::integer;

  if char_length(profile_name) not between 2 and 80
     or birth_year_value < 1900
     or birth_year_value > extract(year from current_date)::integer then
    raise exception 'Data pendaftaran tidak valid.';
  end if;

  perform make_date(birth_year_value, birth_month_value, birth_day_value);

  insert into public.profiles(id, email, name, birth_day, birth_month, birth_year)
  values (
    new.id,
    lower(new.email),
    profile_name,
    birth_day_value,
    birth_month_value,
    birth_year_value
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.handle_auth_email_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.email is distinct from old.email then
    update public.profiles
    set email = lower(new.email), updated_at = now()
    where id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
  after update of email on auth.users
  for each row execute function public.handle_auth_email_update();

create or replace function public.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and status = 'active'
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin' and status = 'active'
  );
$$;

