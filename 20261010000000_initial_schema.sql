create or replace function public.submit_password_report(p_email text, p_message text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  email_value text := lower(btrim(coalesce(p_email, '')));
  message_value text := btrim(coalesce(p_message, ''));
  current_user_id uuid := auth.uid();
begin
  if char_length(email_value) not between 3 and 254
     or email_value !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
     or char_length(message_value) not between 1 and 500 then
    raise exception 'Email atau pesan tidak valid.';
  end if;

  if (
    select count(*) from public.password_reports
    where lower(email) = email_value and created_at > now() - interval '1 day'
  ) >= 5 then
    raise exception 'Terlalu banyak permintaan bantuan untuk email ini. Coba lagi besok.';
  end if;

  insert into public.password_reports(user_id, email, message)
  values (
    (select id from public.profiles where lower(email) = email_value limit 1),
    email_value,
    message_value
  );
end;
$$;

create or replace function public.record_site_visit(p_visitor_id uuid, p_session_id uuid, p_page_path text default '/')
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  path_value text := left(regexp_replace(coalesce(p_page_path, '/'), '[^a-zA-Z0-9/_-]', '', 'g'), 120);
begin
  if p_visitor_id is null or p_session_id is null then
    raise exception 'Identitas kunjungan tidak valid.';
  end if;

  insert into public.site_visitors(visitor_id)
  values (p_visitor_id)
  on conflict (visitor_id) do update set last_seen = now();

  insert into public.site_visits(session_id, visitor_id, page_path)
  values (p_session_id, p_visitor_id, coalesce(nullif(path_value, ''), '/'))
  on conflict (session_id) do nothing;
end;
$$;

create or replace function public.get_admin_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not (select public.is_admin()) then
    raise exception 'Akses admin diperlukan.';
  end if;

  return jsonb_build_object(
    'users', (select count(*) from public.profiles where role = 'user'),
    'activeUsers', (select count(*) from public.profiles where role = 'user' and status = 'active'),
    'foods', (select count(*) from public.foods),
    'pendingReports', (select count(*) from public.password_reports where status = 'pending'),
    'visitors', (select count(*) from public.site_visitors),
    'visitsToday', (select count(distinct visitor_id) from public.site_visits where visited_at >= date_trunc('day', now()))
  );
end;
$$;

create or replace function public.list_admin_users(p_search text default '')
returns table (
  id uuid,
  name text,
  email text,
  birth_day smallint,
  birth_month smallint,
  birth_year smallint,
  role text,
  status text,
  created_at timestamptz,
  diary_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not (select public.is_admin()) then
    raise exception 'Akses admin diperlukan.';
  end if;

  return query
  select p.id, p.name, p.email, p.birth_day, p.birth_month, p.birth_year,
         p.role, p.status, p.created_at, count(d.id)
  from public.profiles p
  left join public.diary d on d.user_id = p.id
  where p.role = 'user'
    and (
      nullif(btrim(p_search), '') is null
      or p.name ilike '%' || btrim(p_search) || '%'
      or p.email ilike '%' || btrim(p_search) || '%'
    )
  group by p.id
  order by p.created_at desc;
end;
$$;

create or replace function public.set_user_status(p_user_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select public.is_admin()) then
    raise exception 'Akses admin diperlukan.';
  end if;
  if p_status not in ('active', 'disabled') then
    raise exception 'Status tidak valid.';
  end if;
  if p_user_id = (select auth.uid()) then
    raise exception 'Admin tidak dapat mengubah status akunnya sendiri.';
  end if;

  update public.profiles
  set status = p_status, updated_at = now()
  where id = p_user_id and role = 'user';

  if not found then
    raise exception 'User tidak ditemukan.';
  end if;
end;
$$;

create or replace function public.resolve_password_report(p_report_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select public.is_admin()) then
    raise exception 'Akses admin diperlukan.';
  end if;

  update public.password_reports
  set status = 'resolved', resolved_at = now()
  where id = p_report_id and status = 'pending';

  if not found then
    raise exception 'Laporan tidak ditemukan atau sudah diselesaikan.';
  end if;
end;
$$;

