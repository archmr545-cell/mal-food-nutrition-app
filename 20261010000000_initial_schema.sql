create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null check (char_length(btrim(name)) between 2 and 80),
  birth_day smallint not null check (birth_day between 1 and 31),
  birth_month smallint not null check (birth_month between 1 and 12),
  birth_year smallint not null check (birth_year between 1900 and extract(year from current_date)),
  role text not null default 'user' check (role in ('user', 'admin')),
  status text not null default 'active' check (status in ('active', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.foods (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) between 1 and 120),
  serving text not null check (char_length(btrim(serving)) between 1 and 80),
  calories numeric(8, 2) not null check (calories >= 0),
  protein numeric(8, 2) not null default 0 check (protein >= 0),
  carbs numeric(8, 2) not null default 0 check (carbs >= 0),
  fat numeric(8, 2) not null default 0 check (fat >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.diary (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  food_id bigint not null references public.foods(id) on delete restrict,
  amount numeric(7, 2) not null check (amount > 0 and amount <= 100),
  created_at timestamptz not null default now()
);

create index if not exists diary_user_created_idx on public.diary(user_id, created_at desc);

create table if not exists public.password_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  email text not null,
  message text not null check (char_length(btrim(message)) between 1 and 500),
  status text not null default 'pending' check (status in ('pending', 'resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists password_reports_status_created_idx
  on public.password_reports(status, created_at desc);

create table if not exists public.site_visitors (
  visitor_id uuid primary key,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now()
);

create table if not exists public.site_visits (
  session_id uuid primary key,
  visitor_id uuid not null references public.site_visitors(visitor_id) on delete cascade,
  page_path text not null default '/',
  visited_at timestamptz not null default now()
);

create index if not exists site_visits_visited_at_idx on public.site_visits(visited_at desc);

